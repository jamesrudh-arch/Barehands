#!/usr/bin/env python3
"""B2.2: enemy posture break + finisher opener (bible 4A: 'Posture break on
enemies mirrors Composure on the player'; balance defaults: posture bar 100,
parry posture 30).

- enemy.gd: posture bar (fills from AttackData.posture_damage on landed
  hits, +30 on being parried, regen after 1.5 s). At the cap the enemy
  POSTURE-BREAKS: a long gold stagger during which a heavy reads as the
  FINISHER. Billboard gold bar above the head (code-built, no assets).
- player.gd: the finisher opener - a heavy on a posture-broken enemy
  executes, same as on a nearly-done one.
- tuning.gd: enemy_posture_max, parry_posture_damage, posture_regen_per_s,
  posture_break_seconds.
- style_meter.gd: 'posture' banks real style.
- attack_data.gd: lights and slams now carry posture damage (jab 4 ...
  slam 30); .tres regenerated by gen_attack_data.py.
"""

GAME = "/home/z/my-project/bare-hands"


def patch(path, subs):
    p = GAME + path
    s = open(p).read()
    for old, new in subs:
        assert old in s, "MISS in %s:\n%s" % (path, old[:140])
        s = s.replace(old, new, 1)
    open(p, "w").write(s)
    print("patched %s (%d edits)" % (path, len(subs)))


# ------------------------------------------------------------- enemy.gd ----
patch("/scripts/enemy.gd", [
    # vars
    ("""var _struck := false
var _topple := 0.0""",
     """var _struck := false
var _topple := 0.0
# posture (Batch 2, bible 4A): fills from landed hits and parries; at the
# cap the enemy BREAKS - a long gold stagger that opens the finisher.
var posture := 0.0
var _posture_at := 0  # msec of the last posture damage (regen delay)
var _posture_break := false
var _stagger_dur := 1.4
var _posture_fill: MeshInstance3D = null  # billboard gold bar"""),

    # stagger step honours the duration (parry 1.4 s, break 2.8 s)
    ("""		State.STAGGER:
			_brake(delta)
			if _state_t > 1.4:
				_enter(State.RECOVER)""",
     """		State.STAGGER:
			_brake(delta)
			if _state_t > _stagger_dur:
				_enter(State.RECOVER)"""),

    # _enter clears the break flag when the stagger ends any other way
    ("""func _enter(s: int) -> void:
	state = s
	_state_t = 0.0""",
     """func _enter(s: int) -> void:
	state = s
	_state_t = 0.0
	if s != State.STAGGER:
		_posture_break = false
		_stagger_dur = 1.4"""),

    # posture API + regen + the billboard bar, appended near the helpers
    ("""func _brake(delta: float) -> void:""",
     """## --- posture (Batch 2) ------------------------------------------------------------

func posture_broken() -> bool:
	return _posture_break


## Posture damage from a landed hit or a parry. At the cap: the BREAK -
## a long gold stagger that opens the finisher window.
func _posture_gain(amount: float) -> void:
	if amount <= 0.0 or state in [State.DOWN, State.GRABBED, State.LAUNCHED]:
		return
	_posture_at = Time.get_ticks_msec()
	posture = minf(posture + amount, Tuning.v("enemy_posture_max"))
	if posture >= Tuning.v("enemy_posture_max"):
		posture = 0.0
		_posture_break = true
		_stagger_dur = Tuning.v("posture_break_seconds")
		_enter(State.STAGGER)
		_play("Hit_Head", 0.05, 0.8)
		_flash_white(Color(1.0, 0.85, 0.2), 3.2)  # gold: the tell
		Sound.play("metal_ring_1", -8.0, 0.7)
		Fx.shake(0.3)
		if _style():
			_style().add("posture")
		_posture_flash_bar()


func _posture_step(delta: float) -> void:
	# the bar eases back down once nothing has threatened it for a beat
	if _posture_at > 0 and Time.get_ticks_msec() - _posture_at > 1500:
		posture = maxf(posture - Tuning.v("posture_regen_per_s") * delta, 0.0)
	if _posture_fill != null:
		var frac := clampf(posture / Tuning.v("enemy_posture_max"), 0.0, 1.0)
		_posture_fill.visible = frac > 0.06
		_posture_fill.scale.x = maxf(frac, 0.01)
		_posture_fill.position.x = -0.35 * (1.0 - frac)


## A brief all-bar flash as the break lands (the bar empties, so the
## flash is the cue the window opened).
func _posture_flash_bar() -> void:
	if _posture_fill == null:
		return
	var tw := create_tween()
	_posture_fill.visible = true
	_posture_fill.scale.x = 1.0
	_posture_fill.position.x = 0.0
	tw.tween_interval(0.35)
	tw.tween_callback(func() -> void: _posture_fill.visible = false)


## The billboard: two unshaded quads above the head, gold fill on dark.
func _build_posture_bar() -> void:
	var holder := Node3D.new()
	holder.position = Vector3(0.0, 2.45, 0.0)
	add_child(holder)
	var mk := func(size_x: float, color: Color) -> MeshInstance3D:
		var mi := MeshInstance3D.new()
		var q := QuadMesh.new()
		q.size = Vector2(size_x, 0.07)
		var m := StandardMaterial3D.new()
		m.shading_mode = BaseMaterial3D.SHADING_MODE_UNSHADED
		m.billboard_mode = BaseMaterial3D.BILLBOARD_ENABLED
		m.albedo_color = color
		q.material = m
		mi.mesh = q
		holder.add_child(mi)
		return mi
	mk(0.74, Color(0.05, 0.05, 0.06, 0.85))
	_posture_fill = mk(0.7, Color(1.0, 0.82, 0.25))
	_posture_fill.visible = false


func _brake(delta: float) -> void:"""),

    # build the bar in _ready
    ("""func _ready() -> void:""",
     """func _ready() -> void:
	_build_posture_bar()"""),

    # take_hit: one AttackData load for knockback + posture, applied on
    # non-armoured hits; a break overrides the flinch
    ("""	var dmg := _damage_of(hit_kind)
	# knockback lives in res://attacks/<kind>.tres (x = push along the
	# hit, y = lift, z = lateral); the match below keeps only the
	# reaction identity - anim, flash, launches, DOWN states.
	var knock := AttackData.for_attack(hit_kind).knockback.x""",
     """	var dmg := _damage_of(hit_kind)
	# knockback and posture both live in res://attacks/<kind>.tres
	# (knockback: x = push, y = lift, z = lateral); the match below keeps
	# only the reaction identity - anim, flash, launches, DOWN states.
	var ad := AttackData.for_attack(hit_kind)
	var knock := ad.knockback.x"""),

    ("""	velocity = dir * knock
	if hp <= 0:
		_die(hit_kind)
	elif hit_kind != "knee":
		_enter(State.FLINCH)""",
     """	velocity = dir * knock
	if not armoured_hit:
		_posture_gain(ad.posture_damage)
	if hp <= 0:
		_die(hit_kind)
	elif hit_kind != "knee" and not _posture_break:
		_enter(State.FLINCH)"""),

    # a parried enemy bites off posture too (bible: parry posture 30)
    ("""func parried() -> void:
	Fx.slow_mo(0.7, 0.35)
	var p := _player()""",
     """func parried() -> void:
	Fx.slow_mo(0.7, 0.35)
	_posture_gain(Tuning.v("parry_posture_damage"))
	var p := _player()"""),

    # regen + bar update ride the physics tick
    ("""	_state_t += delta""",
     """	_state_t += delta
	_posture_step(delta)"""),
])

