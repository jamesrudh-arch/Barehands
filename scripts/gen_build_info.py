#!/usr/bin/env python3
"""The authoritative build-identity generator (Batch 2, the B18/B20
discrepancy fix).

WHY THIS EXISTS: scripts/build_info.gd is the single source of truth
for "which build is this?" - the BuildStamp autoload, the debug menu,
Stage 0, SafeBoot and the DEVICE REPORT all read it. But the file
claimed to be "GENERATED at commit time by scripts/gen_build_info.py"
and THAT SCRIPT DID NOT EXIST in the repository - so through B19 and
B20 the stamping updated only VERSION.txt, and every shipped build
still SAID "B18 e1dfde3" on the phone. This script is the missing
generator. Run it as part of every stamp, after the CODE commit:

    python3 -I scripts/gen_build_info.py <BATCH> [code_commit]

It records: batch, the exact code commit, the build timestamp, the
build configuration, and the target platform - everything Phase 2 of
the master directive requires, from one place.
"""
import pathlib
import subprocess
import sys
import datetime

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "scripts" / "build_info.gd"

BATCH = sys.argv[1] if len(sys.argv) > 1 else "B21"
CONFIG = "xogot-mobile-safe (Mobile renderer, XOGOT SAFE default on iOS)"
PLATFORM = "iPhone via Xogot (Godot 4.7 Mobile/Metal); Linux desktop dev"


def git(args: list) -> str:
    return subprocess.run(["git", "-C", str(ROOT)] + args,
                          capture_output=True, text=True,
                          check=True).stdout.strip()


def main() -> None:
    commit = sys.argv[2] if len(sys.argv) > 2 else git(["rev-parse", "HEAD"])
    commit = commit[:7]
    built = datetime.datetime.now(datetime.timezone.utc).strftime(
        "%Y-%m-%d %H:%M UTC")
    stamp = f"{BATCH} {commit} ({built})"
    body = f'''class_name BuildInfo
## GENERATED by scripts/gen_build_info.py at stamp time - never hand-edit.
## The build stamp is the single source of truth for "which build is
## this?". It is shown at boot (top-right corner, the BuildStamp
## autoload), in the debug menu, on Stage 0, in the SafeBoot log and in
## the DEVICE REPORT. COMMIT is the CODE commit this build runs; the
## stamp commit itself lands one above it (see VERSION.txt at the root).
const BATCH := "{BATCH}"
const COMMIT := "{commit}"
const BUILT := "{built}"
const STAMP := "{stamp}"
const CONFIG := "{CONFIG}"
const PLATFORM := "{PLATFORM}"
'''
    OUT.write_text(body)
    print(f"build_info.gd written: {stamp}")


if __name__ == "__main__":
    main()
